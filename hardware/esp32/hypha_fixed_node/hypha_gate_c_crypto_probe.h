inline Result verifyBlindIssuedVector() {
  Result result{0, 0, 0, 0};
  const uint32_t started = micros();
  uint8_t digest[64]{};
  result.hashCode = mbedtls_sha512(kToken, 98, digest, 1);
  if (result.hashCode != 0) {
    result.elapsedMicros = micros() - started;
    return result;
  }

  mbedtls_pk_context publicKey;
  mbedtls_pk_init(&publicKey);
  result.parseCode =
      mbedtls_pk_parse_public_key(&publicKey, kIssuerSpki, sizeof(kIssuerSpki));
  if (result.parseCode == 0) {
    const mbedtls_pk_rsassa_pss_options options{MBEDTLS_MD_SHA384, 48};
    result.verifyCode = mbedtls_pk_verify_ext(
        MBEDTLS_PK_RSASSA_PSS, &options, &publicKey, MBEDTLS_MD_SHA384,
        digest, 48, kToken + 98, 256);
  }
  mbedtls_pk_free(&publicKey);
  result.elapsedMicros = micros() - started;
  return result;
}

